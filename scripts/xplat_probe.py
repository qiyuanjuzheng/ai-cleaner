#!/usr/bin/env python3
"""AICL-33 cross-platform probe for AICleanerCore.

Builds AICleanerCore and runs AICleanerCoreTests on non-Apple platforms in two passes:

  raw    - the sources as-is, using a Core-only manifest.
  shimmed - the same, after mechanically guarding Apple-only imports
           (`import Darwin` -> Glibc/Musl/ucrt+WinSDK, `import os` -> #if canImport plus an
           NSLock-based OSAllocatedUnfairLock stand-in, `import SQLite3` -> vendored sqlite
           amalgamation C target), so the compiler gets past the import errors and reports
           the real API gaps, and tests run where it compiles.

The repo itself is never modified: each pass works in a throwaway copy.
Results go to <out>/<pass>-build.log, <pass>-test.log and <out>/summary.json / summary.md.
The script always exits 0; it is a report generator, not a gate.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import time
import urllib.request
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

SQLITE_AMALGAMATION = "https://www.sqlite.org/2026/sqlite-amalgamation-3540100.zip"


PROBE_PRODUCTS = ("aicleaner-core-probe", "sidecar-standin", "hello-essentials", "hello-foundation")
SIDECARS = ("aicleaner-core-probe", "sidecar-standin")


def manifest(with_csqlite: bool, with_probes: bool) -> str:
    csqlite_target = (
        """        .target(
            name: "CSQLite",
            path: "Sources/CSQLite",
            cSettings: [
                .define("SQLITE_THREADSAFE", to: "1"),
                .define("SQLITE_OMIT_LOAD_EXTENSION"),
                .define("SQLITE_DQS", to: "0"),
            ]
        ),
"""
        if with_csqlite
        else ""
    )
    deps = '["CSQLite"]' if with_csqlite else "[]"
    test_deps = '["AICleanerCore", "CSQLite"]' if with_csqlite else '["AICleanerCore"]'
    probe_targets = (
        """        .executableTarget(name: "aicleaner-core-probe", dependencies: ["AICleanerCore"], path: "Probes/aicleaner-core-probe"),
        .executableTarget(name: "sidecar-standin", path: "Probes/sidecar-standin"),
        .executableTarget(name: "hello-essentials", path: "Probes/hello-essentials"),
        .executableTarget(name: "hello-foundation", path: "Probes/hello-foundation"),
"""
        if with_probes
        else ""
    )
    return f"""// swift-tools-version: 6.0
import PackageDescription

// Generated by scripts/xplat_probe.py: Core-only probe manifest.
let package = Package(
    name: "AICleaner",
    defaultLocalization: "zh-Hans",
    platforms: [.macOS(.v14)],
    products: [
        .library(name: "AICleanerCore", targets: ["AICleanerCore"]),
    ],
    targets: [
{csqlite_target}        .target(name: "AICleanerCore", dependencies: {deps}, path: "Sources/AICleanerCore"),
{probe_targets}        .testTarget(
            name: "AICleanerCoreTests",
            dependencies: {test_deps},
            path: "Tests/AICleanerCoreTests"
        ),
    ]
)
"""


# Probe-only fallback so the compiler can get past the `os` lock and report the next gaps.
# AICL-35 replaces this with `Synchronization.Mutex`.
LOCK_SHIM = """#if !canImport(os)
import Foundation

/// Probe-only stand-in for `os.OSAllocatedUnfairLock` (generated by scripts/xplat_probe.py).
public final class OSAllocatedUnfairLock<State>: @unchecked Sendable {
    private let lock = NSLock()
    private var state: State

    public init(initialState: State) { state = initialState }

    public func withLock<R>(_ body: (inout State) throws -> R) rethrows -> R {
        lock.lock()
        defer { lock.unlock() }
        return try body(&state)
    }
}
#endif

#if !canImport(Darwin)
/// Probe-only: not a valid confstr name off Darwin, so confstr fails and the NSTemporaryDirectory fallback runs.
let _CS_DARWIN_USER_TEMP_DIR: Int32 = -1

/// Probe-only: autorelease pools only exist with the Objective-C runtime.
@inline(__always)
func autoreleasepool<Result>(invoking body: () throws -> Result) rethrows -> Result {
    try body()
}

/// Probe-only: CoreFoundation time function is not exported by swift-corelibs Foundation.
@inline(__always)
func CFAbsoluteTimeGetCurrent() -> Double { Date().timeIntervalSinceReferenceDate }

struct ProbeTrashUnavailable: Error, CustomStringConvertible {
    var description: String { "FileManager.trashItem is not implemented on this platform (probe stub)" }
}

extension FileManager {
    /// Probe-only: always throws, never deletes anything. Real per-platform trash lands in AICL-35.
    func trashItem(at url: URL, resultingItemURL outResultingURL: UnsafeMutablePointer<NSURL?>?) throws {
        throw ProbeTrashUnavailable()
    }
}
#endif
"""


def vendor_sqlite(work: Path, cache: Path) -> None:
    cache.mkdir(parents=True, exist_ok=True)
    archive = cache / Path(SQLITE_AMALGAMATION).name
    if not archive.exists():
        urllib.request.urlretrieve(SQLITE_AMALGAMATION, archive)
    target = work / "Sources/CSQLite"
    (target / "include").mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as zf:
        for member in zf.namelist():
            name = Path(member).name
            if name == "sqlite3.c":
                (target / name).write_bytes(zf.read(member))
            elif name in ("sqlite3.h", "sqlite3ext.h"):
                (target / "include" / name).write_bytes(zf.read(member))

SHIMS = [
    (
        re.compile(r"^import Darwin$", re.M),
        "#if canImport(Darwin)\nimport Darwin\n#elseif canImport(Glibc)\nimport Glibc\n"
        "#elseif canImport(Musl)\nimport Musl\n#elseif canImport(ucrt)\nimport ucrt\nimport WinSDK\n#endif",
    ),
    (re.compile(r"^import os$", re.M), "#if canImport(os)\nimport os\n#endif"),
    (re.compile(r"^import SQLite3$", re.M), "#if canImport(SQLite3)\nimport SQLite3\n#else\nimport CSQLite\n#endif"),
]

# Source rewrites that are only valid off Darwin (applied on Linux only; Windows reports them raw).
LINUX_SHIMS = [
    # Linux glibc / musl name the timespec fields st_mtim / st_atim / st_ctim.
    (re.compile(r"\bst_(m|a|c)timespec\b"), r"st_\1tim"),
    # Linux struct stat has no birth time (needs statx); probe substitutes ctime. Semantics differ.
    (re.compile(r"\bst_birthtimespec\b"), "st_ctim"),
    # Test helpers that create Unix domain sockets (TempDirectoryScannerTests).
    (re.compile(r"^(\s*)addr\.sun_len = (.+)$", re.M), r"\1#if canImport(Darwin)\n\1addr.sun_len = \2\n\1#endif"),
    (
        re.compile(r"^(\s*)let fd = socket\(AF_UNIX, SOCK_STREAM, 0\)$", re.M),
        r"\1#if canImport(Glibc) || canImport(Musl)\n\1let fd = socket(AF_UNIX, Int32(SOCK_STREAM.rawValue), 0)"
        r"\n\1#else\n\1let fd = socket(AF_UNIX, SOCK_STREAM, 0)\n\1#endif",
    ),
    (re.compile(r"\bDarwin\.bind\("), "bind("),
]

DIAG_RE = re.compile(
    r"^(?P<file>(?:[A-Za-z]:)?[^:\n]*?\.swift):(?P<line>\d+):(?P<col>\d+):\s*(?P<kind>error|warning):\s*(?P<msg>.+)$"
)
ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")


def run(cmd: list[str], cwd: Path, log: Path, timeout: int) -> tuple[int, float]:
    start = time.time()
    with log.open("w", encoding="utf-8", errors="replace") as fh:
        fh.write(f"$ {' '.join(cmd)}\n")
        fh.flush()
        try:
            proc = subprocess.run(cmd, cwd=cwd, stdout=fh, stderr=subprocess.STDOUT, timeout=timeout)
            code = proc.returncode
        except subprocess.TimeoutExpired:
            fh.write(f"\n[probe] timeout after {timeout}s\n")
            code = 124
        except FileNotFoundError as exc:
            fh.write(f"\n[probe] {exc}\n")
            code = 127
    return code, round(time.time() - start, 1)


def prepare(work: Path, shim: bool, cache: Path) -> int:
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    for sub in ("Sources/AICleanerCore", "Tests/AICleanerCoreTests"):
        shutil.copytree(REPO / sub, work / sub)
    # Apple platforms keep the system SQLite3 module; elsewhere the amalgamation is vendored.
    csqlite = shim and sys.platform != "darwin"
    (work / "Package.swift").write_text(manifest(with_csqlite=csqlite, with_probes=shim), encoding="utf-8")
    changed = 0
    if shim:
        shutil.copytree(REPO / "scripts/xplat-probe", work / "Probes", ignore=shutil.ignore_patterns("tauri-shell"))
        if csqlite:
            vendor_sqlite(work, cache)
        (work / "Sources/AICleanerCore/ProbeShims.swift").write_text(LOCK_SHIM, encoding="utf-8")
        for path in work.rglob("*.swift"):
            if path.name == "Package.swift":
                continue
            text = path.read_text(encoding="utf-8")
            new = text
            rules = SHIMS + (LINUX_SHIMS if sys.platform.startswith("linux") else [])
            for pattern, repl in rules:
                new = pattern.sub(repl, new)
            if new != text:
                path.write_text(new, encoding="utf-8")
                changed += 1
    return changed


def parse(log: Path, work: Path) -> list[dict]:
    seen: set[tuple] = set()
    diags: list[dict] = []
    root = str(work).replace("\\", "/").rstrip("/") + "/"
    for raw in log.read_text(encoding="utf-8", errors="replace").splitlines():
        line = ANSI_RE.sub("", raw).strip()
        m = DIAG_RE.match(line)
        if not m or m["kind"] != "error":
            continue
        file = m["file"].replace("\\", "/")
        if file.startswith(root):
            file = file[len(root):]
        else:
            idx = file.find("Sources/")
            idx = idx if idx >= 0 else file.find("Tests/")
            file = file[idx:] if idx >= 0 else file
        key = (file, m["line"], m["msg"])
        if key in seen:
            continue
        seen.add(key)
        diags.append({"file": file, "line": int(m["line"]), "message": m["msg"]})
    return diags


def test_counts(log: Path) -> dict:
    text = ANSI_RE.sub("", log.read_text(encoding="utf-8", errors="replace"))
    out: dict = {}
    m = re.findall(r"Executed (\d+) tests?, with (\d+) failures?", text)
    if m:
        out["executed"], out["failures"] = int(m[-1][0]), int(m[-1][1])
    failed = sorted(set(re.findall(r"Test Case '-\[\S+ (\S+)\]' failed|Test Case '(\S+)' failed", text)))
    out["failed_cases"] = sorted({a or b for a, b in failed})
    return out


# ---------------------------------------------------------------------------
# Size / memory measurement (runs after a successful shimmed build)
# ---------------------------------------------------------------------------

EXE = ".exe" if os.name == "nt" else ""


def mib(n: int | None) -> float | None:
    return None if n is None else round(n / 1024 / 1024, 2)


def pe_imports(path: Path) -> list[str]:
    """Minimal PE import-table reader (DLL names only), so no pefile/dumpbin dependency."""
    import struct

    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    optsize = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    ddir = opt + (112 if magic == 0x20B else 96)
    imp_rva = struct.unpack_from("<I", data, ddir + 8)[0]
    sections = []
    sec = opt + optsize
    for i in range(nsec):
        vsize, va, raw_size, raw_ptr = struct.unpack_from("<IIII", data, sec + i * 40 + 8)
        sections.append((va, max(vsize, raw_size), raw_ptr))

    def off(rva: int) -> int | None:
        for va, size, ptr in sections:
            if va <= rva < va + size:
                return rva - va + ptr
        return None

    names: list[str] = []
    cur = off(imp_rva) if imp_rva else None
    while cur is not None:
        name_rva = struct.unpack_from("<I", data, cur + 12)[0]
        if name_rva == 0:
            break
        noff = off(name_rva)
        if noff is None:
            break
        end = data.index(b"\0", noff)
        names.append(data[noff:end].decode("ascii", "replace"))
        cur += 20
    return names


def windows_runtime_closure(binary: Path) -> dict:
    """Walk PE imports and keep the DLLs that ship with the Swift runtime (not system DLLs)."""
    search = [Path(p) for p in os.environ.get("PATH", "").split(os.pathsep) if p]
    system_root = Path(os.environ.get("SystemRoot", r"C:\Windows")).resolve()
    seen: dict[str, Path] = {}
    queue = [binary]
    while queue:
        cur = queue.pop()
        try:
            deps = pe_imports(cur)
        except Exception:  # noqa: BLE001 - best effort probe
            continue
        for dll in deps:
            key = dll.lower()
            if key in seen or key.startswith(("api-ms-", "ext-ms-")):
                continue
            hit = next((d / dll for d in search if (d / dll).is_file()), None)
            if hit is None:
                continue
            # Keep only what ships with the Swift toolchain / runtime installer; system and
            # VC++ redistributable DLLs are outside the Swift runtime closure.
            if hit.resolve().is_relative_to(system_root) or "swift" not in str(hit).lower():
                continue
            seen[key] = hit
            queue.append(hit)
    files = {k: v.stat().st_size for k, v in sorted(seen.items())}
    return {
        "dlls": {k: mib(v) for k, v in files.items()},
        "paths": {k: str(v) for k, v in sorted(seen.items())},
        "total_mib": mib(sum(files.values())),
    }


def elf_runtime_closure(binary: Path) -> dict:
    proc = subprocess.run(["ldd", str(binary)], capture_output=True, text=True)
    files: dict[str, int] = {}
    for line in proc.stdout.splitlines():
        m = re.search(r"=>\s+(\S+)", line)
        if not m:
            continue
        lib = Path(m.group(1))
        if lib.exists() and ("swift" in str(lib) or lib.name.startswith(("libFoundation", "lib_Foundation", "libdispatch", "libBlocksRuntime"))):
            files[lib.name] = lib.resolve().stat().st_size
    return {"libs": {k: mib(v) for k, v in sorted(files.items())}, "total_mib": mib(sum(files.values()))}


def idle_rss(binary: Path, settle: float = 3.0) -> int | None:
    """Start the sidecar, send hello, wait, read resident memory of the idle process."""
    proc = subprocess.Popen([str(binary)], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True)
    try:
        assert proc.stdin and proc.stdout
        proc.stdin.write('{"jsonrpc":"2.0","id":1,"method":"hello"}\n')
        proc.stdin.flush()
        proc.stdout.readline()
        time.sleep(settle)
        pid = proc.pid
        if sys.platform.startswith("linux"):
            for line in Path(f"/proc/{pid}/status").read_text().splitlines():
                if line.startswith("VmRSS:"):
                    return int(line.split()[1]) * 1024
        elif os.name == "nt":
            out = subprocess.run(
                ["powershell", "-NoProfile", "-Command", f"(Get-Process -Id {pid}).WorkingSet64"],
                capture_output=True, text=True,
            ).stdout.strip()
            return int(out) if out.isdigit() else None
        else:
            out = subprocess.run(["ps", "-o", "rss=", "-p", str(pid)], capture_output=True, text=True).stdout.strip()
            return int(out) * 1024 if out.isdigit() else None
    except Exception:  # noqa: BLE001
        return None
    finally:
        try:
            if proc.stdin:
                proc.stdin.write('{"jsonrpc":"2.0","id":2,"method":"shutdown"}\n')
                proc.stdin.flush()
            proc.wait(timeout=5)
        except Exception:  # noqa: BLE001
            proc.kill()
    return None


def measure(work: Path, out: Path, swift: str, timeout: int, extra: list[list[str]], core_ok: bool) -> dict:
    """Release-build the probe executables in each requested configuration and record sizes."""
    configs: list[tuple[str, list[str]]] = [("dynamic", [])]
    if sys.platform.startswith("linux"):
        configs.append(("static-stdlib", ["--static-swift-stdlib"]))
    for flags in extra:
        configs.append((" ".join(flags), flags))
    results: dict = {}
    for label, flags in configs:
        safe = re.sub(r"[^A-Za-z0-9]+", "_", label).strip("_")
        log = out / f"measure-{safe}.log"
        scratch = work / f".build-{safe}"
        base = [swift, "build", "-c", "release", "--scratch-path", str(scratch), *flags]
        entry: dict = {"flags": flags}
        products: dict = {}
        bin_dir = subprocess.run([*base, "--show-bin-path"], cwd=work, capture_output=True, text=True).stdout.strip()
        # `--product` builds only that product's dependency closure, so the Core-free probes
        # still measure on platforms where AICleanerCore does not compile yet.
        for product in PROBE_PRODUCTS if core_ok else PROBE_PRODUCTS[1:]:
            code, secs = run([*base, "--product", product], work, log.with_name(f"{log.stem}-{product}.log"), timeout)
            binary = Path(bin_dir) / f"{product}{EXE}" if bin_dir else None
            info: dict = {"build_exit": code, "build_seconds": secs}
            if code == 0 and binary and binary.exists():
                if os.name != "nt":
                    stripped = binary.with_name(binary.name + ".stripped")
                    shutil.copy2(binary, stripped)
                    subprocess.run(["strip", str(stripped)], capture_output=True)
                    info["stripped_mib"] = mib(stripped.stat().st_size)
                info["binary_mib"] = mib(binary.stat().st_size)
                if os.name == "nt":
                    info["runtime"] = windows_runtime_closure(binary)
                elif sys.platform.startswith("linux"):
                    info["runtime"] = elf_runtime_closure(binary)
                if product in SIDECARS:
                    rss = idle_rss(binary)
                    info["idle_rss_mib"] = mib(rss)
                    hello = subprocess.run([str(binary), "--once", "hello"], capture_output=True, text=True)
                    info["hello"] = hello.stdout.strip()
                    dest = out / "bin" / safe
                    dest.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(binary, dest / binary.name)
            products[product] = info
        entry["products"] = products
        results[label] = entry
    return results


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(REPO / ".build-probe"))
    ap.add_argument("--work", default=None, help="scratch dir (default: <out>/work)")
    ap.add_argument("--passes", default="raw,shimmed")
    ap.add_argument("--timeout", type=int, default=2400)
    ap.add_argument("--skip-tests", action="store_true")
    ap.add_argument("--measure", action="store_true", help="release-build probe executables and record sizes")
    ap.add_argument(
        "--extra-build", action="append", default=[],
        help="extra measured build config, e.g. --extra-build='--swift-sdk aarch64-swift-linux-musl'",
    )
    args = ap.parse_args()

    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    work_root = Path(args.work).resolve() if args.work else out / "work"
    swift = shutil.which("swift") or "swift"
    ver = subprocess.run([swift, "--version"], capture_output=True, text=True)
    summary: dict = {
        "platform": f"{platform.system()} {platform.machine()}",
        "swift": (ver.stdout or ver.stderr).strip().splitlines()[0] if (ver.stdout or ver.stderr) else "?",
        "passes": {},
    }

    for name in [p.strip() for p in args.passes.split(",") if p.strip()]:
        work = work_root / name
        shimmed_files = prepare(work, shim=(name == "shimmed"), cache=out / "cache")
        res: dict = {"shimmed_files": shimmed_files}
        build_log = out / f"{name}-build.log"
        code, secs = run([swift, "build", "--build-tests"], work, build_log, args.timeout)
        res.update(build_exit=code, build_seconds=secs, errors=parse(build_log, work))
        if code == 0 and not args.skip_tests:
            test_log = out / f"{name}-test.log"
            tcode, tsecs = run([swift, "test", "--skip-build"], work, test_log, args.timeout)
            res.update(test_exit=tcode, test_seconds=tsecs, **test_counts(test_log))
        if name == "shimmed" and args.measure:
            res["measure"] = measure(
                work, out, swift, args.timeout, [e.split() for e in args.extra_build], core_ok=(code == 0)
            )
        summary["passes"][name] = res
        print(f"[probe] {name}: build_exit={code} errors={len(res['errors'])}", flush=True)

    (out / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    md = [f"## AICleanerCore probe — {summary['platform']}", "", f"`{summary['swift']}`", ""]
    for name, res in summary["passes"].items():
        md.append(f"### {name}: build exit {res['build_exit']}, {len(res['errors'])} distinct errors")
        if "executed" in res:
            md.append(f"tests: {res['executed']} executed, {res['failures']} failures")
            for case in res.get("failed_cases", []):
                md.append(f"- failed: `{case}`")
        md.append("")
        md.append("| file:line | error |")
        md.append("|---|---|")
        for d in res["errors"]:
            msg = d["message"].replace("|", "\\|")
            md.append(f"| `{d['file']}:{d['line']}` | {msg} |")
        md.append("")
        if "measure" in res:
            md.append("| config | product | binary MiB | stripped MiB | runtime libs MiB | idle RSS MiB |")
            md.append("|---|---|---|---|---|---|")
            for label, entry in res["measure"].items():
                for product, info in entry["products"].items():
                    rt = (info.get("runtime") or {}).get("total_mib")
                    md.append(
                        f"| {label} | {product} | {info.get('binary_mib', 'build ' + str(info['build_exit']))} | "
                        f"{info.get('stripped_mib', '-')} | {rt if rt is not None else '-'} | {info.get('idle_rss_mib', '-')} |"
                    )
            md.append("")
    (out / "summary.md").write_text("\n".join(md), encoding="utf-8")
    step = os.environ.get("GITHUB_STEP_SUMMARY")
    if step:
        with open(step, "a", encoding="utf-8") as fh:
            fh.write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
    sys.exit(0)
